def main():
    rows = list(csv.DictReader(io.open(SRC, encoding="utf-8-sig")))
    before = len(rows)
    used = {int(r["id"]) for r in rows}
    next_id = max(used) + 1

    for item in NEW:
        title, ctype, industry, city, jtype, degree, major, must, plus, duties, salary = item
        if any(r["job_title"] == title for r in rows):
            print("跳过重名岗位：%s" % title)
            continue
        rows.append({
            "id": str(next_id), "job_title": title, "company_type": ctype,
            "industry": industry, "city": city, "job_type": jtype, "degree": degree,
            "major_req": major, "must_skills": must, "plus_skills": plus,
            "duties": duties, "salary_range": salary, "updated_at": "2026-10",
        })
        next_id += 1

    with io.open(OUT, "w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(rows)
    print("%d -> %d 个岗位，已写出 %s" % (before, len(rows), OUT))

    missing = [k for k in FIELDS if any(not (r.get(k) or "").strip() for r in rows)]
    print("空字段检查：%s" % ("全部有值 ✅" if not missing else "存在空值 %s ❌" % missing))
    dup = {r["job_title"] for r in rows}
    print("岗位名唯一性：%d 个名称 / %d 行 %s" % (len(dup), len(rows), "✅" if len(dup) == len(rows) else "❌"))


if __name__ == "__main__":
    main()
